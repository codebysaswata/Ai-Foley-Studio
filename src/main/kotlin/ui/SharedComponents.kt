private val ButtonShape18 = RoundedCornerShape(18.dp)

@Composable
internal fun StaticButton(
    label: String,
    dark: Boolean,
    padding: PaddingValues = PaddingValues(horizontal = 30.dp, vertical = 19.dp),
    fontSize: androidx.compose.ui.unit.TextUnit = 20.sp,
    enableHoverLift: Boolean = false,
    onClick: (() -> Unit)? = null
) {
    val interactionSource = remember { MutableInteractionSource() }
    val hovered by interactionSource.collectIsHoveredAsState()
    val hoverOffset by animateDpAsState(
        targetValue = if (enableHoverLift && hovered) (-5).dp else 0.dp,
        animationSpec = tween(180, easing = FastOutSlowInEasing),
        label = "buttonHoverLift$label"
    )
    val elevation by animateDpAsState(
        targetValue = if (enableHoverLift && hovered) 9.dp else 0.dp,
        animationSpec = tween(180, easing = FastOutSlowInEasing),
        label = "buttonHoverShadow$label"
    )
    Box(
        modifier = Modifier.heightIn(min = 58.dp)
            .graphicsLayer {
                translationY = hoverOffset.toPx()
                shadowElevation = elevation.toPx()
                shape = ButtonShape18
                clip = false
            }
            .then(if (enableHoverLift) Modifier.hoverable(interactionSource) else Modifier)
            .clip(RoundedCornerShape(18.dp))
            .background(if (dark) Burgundy else CanvasCream)
            .then(if (dark) Modifier else Modifier.border(2.dp, Burgundy, RoundedCornerShape(18.dp)))
            .then(if (onClick != null) Modifier.clickable(interactionSource = interactionSource, indication = null, onClick = onClick) else Modifier)
            .padding(padding),
        contentAlignment = Alignment.Center
    ) {
        Text(label, color = if (dark) Color.White else Burgundy, fontSize = fontSize, fontWeight = FontWeight.Medium)
    }
}

